import { LogicBlock, LevelObject, Vector3D } from '../types/game';

export interface ScriptCommand {
  lineNum?: number;
  type: 'MOVE' | 'ROTATE' | 'WAIT' | 'GOTO' | 'COLOR' | 'SPEED' | 'TELEPORT' | 'TRIGGER' | 'WIN' | 'PLAY_SOUND' | 'UNKNOWN';
  raw: string;
  target?: string;
  axis?: 'x' | 'y' | 'z';
  value?: number;
  vector?: Vector3D;
  strValue?: string;
  error?: string;
}

export interface ParseResult {
  valid: boolean;
  commands: ScriptCommand[];
  errors: string[];
}

export class BasicScriptEngine {
  /**
   * Parse BASIC code text into structured commands
   */
  public static parse(code: string): ParseResult {
    const lines = code.split('\n');
    const commands: ScriptCommand[] = [];
    const errors: string[] = [];

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i].trim();
      if (!line || line.startsWith('REM') || line.startsWith('#') || line.startsWith('//')) {
        continue; // skip comments
      }

      // Check optional line number: e.g. "10 MOVE X 5"
      const match = line.match(/^(\d+)?\s*(.*)$/);
      if (!match) continue;

      const lineNum = match[1] ? parseInt(match[1], 10) : undefined;
      const statement = (match[2] || '').trim();
      if (!statement) continue;

      const tokens = statement.split(/\s+/);
      const opcode = tokens[0].toUpperCase();

      if (opcode === 'MOVE') {
        // MOVE [AXIS] [VALUE] or MOVE [TARGET] [AXIS] [VALUE]
        let axis: 'x' | 'y' | 'z' = 'x';
        let val = 5;
        let target: string | undefined;

        if (tokens.length >= 4) {
          target = tokens[1];
          axis = (tokens[2].toLowerCase() as 'x' | 'y' | 'z') || 'x';
          val = parseFloat(tokens[3]) || 0;
        } else if (tokens.length >= 3) {
          axis = (tokens[1].toLowerCase() as 'x' | 'y' | 'z') || 'x';
          val = parseFloat(tokens[2]) || 0;
        }

        commands.push({
          lineNum,
          type: 'MOVE',
          raw: line,
          target,
          axis,
          value: val
        });
      } else if (opcode === 'ROTATE') {
        // ROTATE [AXIS] [DEG]
        const axis = (tokens[1]?.toLowerCase() as 'x' | 'y' | 'z') || 'y';
        const val = parseFloat(tokens[2]) || 90;
        commands.push({
          lineNum,
          type: 'ROTATE',
          raw: line,
          axis,
          value: val
        });
      } else if (opcode === 'WAIT' || opcode === 'SLEEP') {
        const val = parseFloat(tokens[1]) || 1;
        commands.push({
          lineNum,
          type: 'WAIT',
          raw: line,
          value: val
        });
      } else if (opcode === 'GOTO') {
        const targetLine = parseInt(tokens[1], 10);
        if (isNaN(targetLine)) {
          errors.push(`Line ${lineNum || i + 1}: Invalid GOTO destination '${tokens[1]}'`);
        } else {
          commands.push({
            lineNum,
            type: 'GOTO',
            raw: line,
            value: targetLine
          });
        }
      } else if (opcode === 'COLOR') {
        const color = tokens[1] || '#ff0055';
        commands.push({
          lineNum,
          type: 'COLOR',
          raw: line,
          strValue: color
        });
      } else if (opcode === 'TELEPORT') {
        const x = parseFloat(tokens[1]) || 0;
        const y = parseFloat(tokens[2]) || 2;
        const z = parseFloat(tokens[3]) || 0;
        commands.push({
          lineNum,
          type: 'TELEPORT',
          raw: line,
          vector: { x, y, z }
        });
      } else if (opcode === 'WIN') {
        commands.push({
          lineNum,
          type: 'WIN',
          raw: line
        });
      } else if (opcode === 'SOUND' || opcode === 'PLAY_SOUND') {
        const sound = tokens[1] || 'victory';
        commands.push({
          lineNum,
          type: 'PLAY_SOUND',
          raw: line,
          strValue: sound
        });
      } else if (opcode === 'ON') {
        // ON TOUCH / ON TIMER 2
        commands.push({
          lineNum,
          type: 'TRIGGER',
          raw: line,
          strValue: statement
        });
      } else {
        errors.push(`Line ${lineNum || i + 1}: Unknown command '${opcode}'`);
        commands.push({
          lineNum,
          type: 'UNKNOWN',
          raw: line,
          error: `Unknown command '${opcode}'`
        });
      }
    }

    return {
      valid: errors.length === 0,
      commands,
      errors
    };
  }

  /**
   * Convert Logic Blocks to BASIC text representation
   */
  public static blocksToBasic(blocks: LogicBlock[]): string {
    let script = '10 REM --- GENERATED BY VISUAL BLOCK BUILDER ---\n';
    let lineNum = 20;

    for (const b of blocks) {
      if (b.trigger === 'ON_TIMER') {
        script += `${lineNum} ON TIMER ${b.triggerParam || 2}\n`;
        lineNum += 10;
      } else if (b.trigger === 'ON_TOUCH') {
        script += `${lineNum} ON TOUCH\n`;
        lineNum += 10;
      }

      if (b.action === 'MOVE') {
        script += `${lineNum} MOVE ${b.actionParams?.axis?.toUpperCase() || 'X'} ${b.actionParams?.amount || 5}\n`;
        lineNum += 10;
        script += `${lineNum} WAIT 1.5\n`;
        lineNum += 10;
        script += `${lineNum} MOVE ${b.actionParams?.axis?.toUpperCase() || 'X'} ${-(b.actionParams?.amount || 5)}\n`;
        lineNum += 10;
      } else if (b.action === 'ROTATE') {
        script += `${lineNum} ROTATE ${b.actionParams?.axis?.toUpperCase() || 'Y'} ${b.actionParams?.amount || 90}\n`;
        lineNum += 10;
      } else if (b.action === 'PLAY_SOUND') {
        script += `${lineNum} SOUND ${b.actionParams?.soundName || 'coin'}\n`;
        lineNum += 10;
      } else if (b.action === 'WIN_GAME') {
        script += `${lineNum} WIN\n`;
        lineNum += 10;
      }
    }

    script += `${lineNum} GOTO 20\n`;
    return script;
  }

  /**
   * Convert BASIC Script code to Visual Blocks
   */
  public static basicToBlocks(code: string): LogicBlock[] {
    const parse = this.parse(code);
    const blocks: LogicBlock[] = [];

    for (const cmd of parse.commands) {
      if (cmd.type === 'MOVE') {
        blocks.push({
          id: 'blk_' + Math.random().toString(36).substring(2, 9),
          trigger: 'ON_START',
          action: 'MOVE',
          actionParams: {
            axis: cmd.axis || 'x',
            amount: cmd.value || 5,
            speed: 2
          }
        });
      } else if (cmd.type === 'ROTATE') {
        blocks.push({
          id: 'blk_' + Math.random().toString(36).substring(2, 9),
          trigger: 'ON_START',
          action: 'ROTATE',
          actionParams: {
            axis: cmd.axis || 'y',
            amount: cmd.value || 90
          }
        });
      } else if (cmd.type === 'PLAY_SOUND') {
        blocks.push({
          id: 'blk_' + Math.random().toString(36).substring(2, 9),
          trigger: 'ON_TOUCH',
          action: 'PLAY_SOUND',
          actionParams: {
            soundName: cmd.strValue || 'coin'
          }
        });
      } else if (cmd.type === 'WIN') {
        blocks.push({
          id: 'blk_' + Math.random().toString(36).substring(2, 9),
          trigger: 'ON_TOUCH',
          action: 'WIN_GAME'
        });
      }
    }

    return blocks;
  }
}
